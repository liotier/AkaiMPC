#!/usr/bin/env node
/**
 * Catalogue snapshot: a committed, human-readable record of what every
 * progression template and every scale actually sounds like.
 *
 * Run with:
 *   node tools/catalogue-snapshot.mjs --write    regenerate docs/catalogue-snapshot.txt
 *   node tools/catalogue-snapshot.mjs --check    exit 1 if a regeneration would differ
 *
 * Why it exists: tools/audit-theory.mjs proves that every pad agrees with its
 * own label - notes against type, type against name, numeral against root.
 * That is necessary and not sufficient. It passed while twelve minor-key
 * templates played leading-tone major triads where their nicknames promise
 * subtonic chords, because under the engine's convention the label and the
 * chord agreed perfectly: nothing recorded what the catalogue sounds like. The
 * published pack is byte-identical across builds, which proves "nothing
 * changed" and cannot say which chord moved. This snapshot is the missing
 * artefact: a change to the catalogue lands as a diff of chord names that a
 * person can read.
 *
 * The rule that goes with it: a change to what the catalogue produces ships
 * with its regenerated snapshot, and the diff of the snapshot is what gets
 * reviewed. CI runs --check (.github/workflows/check-theory.yml). The format
 * and the decisions behind it are in docs/improvements/00-catalogue-snapshot.md.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { progressions, modes, findModeCategory } from '../modules/musicTheory.js';
import { generateVariant, generateScaleExploration } from '../modules/generation.js';
import { unifiedDiff, splitLines } from './lib/unified-diff.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SNAPSHOT_RELATIVE = 'docs/catalogue-snapshot.txt';
const SNAPSHOT_PATH = join(ROOT, 'docs', 'catalogue-snapshot.txt');

// Major-tonality templates are rendered in C and minor-tonality ones in A, so
// the diatonic chords carry no accidentals and a diff reads as music rather
// than as enharmonic respelling (D3). Scales are all shown in C.
const MAJOR_KEY = 'C';
const MINOR_KEY = 'A';
const SCALE_KEY = 'C';

// The em dash that joins the chords of a template value ('I—V—vi—IV')
const CHORD_SEPARATOR = '—';

const LABEL_WIDTH = 7; // 'Classic' is the longest label
const RANGE_WIDTH = 5; // '13-16'
const DIFF_LINES_SHOWN = 40;
const CHANGED_BLOCKS_LISTED = 10;
const FIX_HINT = 'Run with --write and commit the result if the change is intended.';

const HEADER_LINES = [
    '# Catalogue snapshot. Generated by tools/catalogue-snapshot.mjs - do not edit by hand.',
    '# Templates: Classic and Jazz variants, in C for major tonality, in A for minor.',
    '# A leading * marks a progression chord. Smooth voicings are MIDI note numbers.'
];

const en = JSON.parse(readFileSync(join(ROOT, 'locales', 'en.json'), 'utf8'));

// ============================================================================
// Template tonality
// ============================================================================

/**
 * Whether a template is in a major or a minor key. An explicit `tonality` on
 * the template wins; until templates carry one, the first token whose stem is
 * a bare I or i decides, by its case. Tokens with a slash are applied chords
 * (V7/ii), and a token with an accidental or a longer stem (♭III, IV, ii) is
 * not the tonic. A template with no tonic token at all renders as major.
 *
 * @param {Object} template - A progressions[category] entry
 * @returns {'major'|'minor'}
 */
function templateTonality(template) {
    if (template.tonality !== undefined) {
        if (template.tonality !== 'major' && template.tonality !== 'minor') {
            throw new Error(`Template ${template.value}: tonality must be 'major' or 'minor', got ${JSON.stringify(template.tonality)}`);
        }
        return template.tonality;
    }

    for (const token of template.value.split(CHORD_SEPARATOR)) {
        if (token.includes('/')) continue;
        const tonic = token.match(/^([iI])(?![ivIV])/);
        if (tonic) return tonic[1] === 'i' ? 'minor' : 'major';
    }
    return 'major';
}

// ============================================================================
// Formatting
// ============================================================================

const formatPad = pad => `${pad.isProgressionChord ? '*' : ''}${pad.chordName} [${pad.romanNumeral}]`;

/**
 * One line of a block: a label, the pad range it covers, and its content.
 * The first pad number is right-aligned so the units digits line up
 * (' 1-4', ' 9-12', '13-16') and the content always starts in the same column.
 */
function blockLine(label, firstPad, content) {
    const range = `${String(firstPad).padStart(2)}-${firstPad + 3}`.padEnd(RANGE_WIDTH);
    return `${label.padEnd(LABEL_WIDTH)} ${range}  ${content}`;
}

/** Four lines, one per row of the 4x4 grid, showing every pad of a variant. */
function rowLines(label, pads) {
    const lines = [];
    for (let row = 0; row < 4; row++) {
        const content = pads.slice(row * 4, row * 4 + 4).map(formatPad).join('  ');
        lines.push(blockLine(label, row * 4 + 1, content));
    }
    return lines;
}

/**
 * The sixteen pads of a generated variant, refusing anything that is not a
 * complete grid. A blank cell in a snapshot would read as a stylistic choice;
 * it is better to stop.
 */
function checkedPads(variant, where) {
    const pads = variant?.pads;
    if (!Array.isArray(pads) || pads.length !== 16) {
        throw new Error(`${where}: expected 16 pads, got ${Array.isArray(pads) ? pads.length : 'none'}`);
    }
    pads.forEach((pad, index) => {
        if (!pad.chordName || !pad.romanNumeral || !Array.isArray(pad.notes) || pad.notes.length === 0) {
            throw new Error(`${where}: pad ${index + 1} has no chord name, roman numeral or notes`);
        }
    });
    return pads;
}

// ============================================================================
// Blocks
// ============================================================================

function templateBlock(category, template) {
    const { value } = template;
    const nickname = en.progressions?.[category]?.[value]?.nickname;
    if (!nickname) throw new Error(`locales/en.json has no nickname for ${category} | ${value}`);

    const tonality = templateTonality(template);
    const key = tonality === 'minor' ? MINOR_KEY : MAJOR_KEY;
    const header = `## ${category} | ${value} | ${nickname} | ${tonality} | ${key}`;

    // The category selects which genre's entry is generated: a value listed
    // under several genres has its own palette priorities in each, so their
    // blocks differ wherever those priorities do
    // (docs/improvements/01-template-identity.md).
    const generate = style => checkedPads(
        generateVariant(style, { key, mode: 'Major', progression: value, category, chordRequirements: [] }),
        `${header} / ${style}`
    );

    const classic = generate('Classic');
    const jazz = generate('Jazz');
    const smooth = generate('Smooth');

    return {
        header,
        lines: [
            header,
            ...rowLines('Classic', classic),
            ...rowLines('Jazz', jazz),
            blockLine('Smooth', 1, smooth.slice(0, 4).map(pad => pad.notes.join(',')).join(' | '))
        ]
    };
}

function scaleBlock(mode) {
    const category = findModeCategory(mode);
    if (!category) throw new Error(`Scale ${mode} belongs to no category in the modes object`);

    const header = `## Scale | ${mode} | ${category} | ${SCALE_KEY}`;
    const exploration = generateScaleExploration({ key: SCALE_KEY, mode });
    return { header, lines: [header, ...rowLines('Pads', checkedPads(exploration, header))] };
}

/** The whole snapshot: text, plus the counts the summary lines report. */
function buildSnapshot() {
    const blocks = [];
    const seen = new Set();
    const add = block => {
        if (seen.has(block.header)) throw new Error(`Two blocks share the header "${block.header}"`);
        seen.add(block.header);
        blocks.push(block);
    };

    let templateCount = 0;
    for (const [category, list] of Object.entries(progressions)) {
        for (const template of list) {
            add(templateBlock(category, template));
            templateCount++;
        }
    }

    let scaleCount = 0;
    for (const list of Object.values(modes)) {
        for (const mode of list) {
            add(scaleBlock(mode));
            scaleCount++;
        }
    }

    const lines = [...HEADER_LINES];
    for (const block of blocks) lines.push('', ...block.lines);

    return { text: lines.join('\n') + '\n', templateCount, scaleCount, lineCount: lines.length };
}

// ============================================================================
// Modes
// ============================================================================

/** header line -> the block's lines joined, for comparing two snapshots block by block */
function parseBlocks(text) {
    const blocks = new Map();
    let current = null;
    for (const line of splitLines(text)) {
        if (line.startsWith('## ')) {
            current = line;
            blocks.set(current, []);
        } else if (current !== null && line !== '') {
            blocks.get(current).push(line);
        }
    }
    return new Map([...blocks].map(([header, body]) => [header, body.join('\n')]));
}

function write(snapshot) {
    mkdirSync(dirname(SNAPSHOT_PATH), { recursive: true });
    writeFileSync(SNAPSHOT_PATH, snapshot.text);
    console.log(`Wrote ${SNAPSHOT_RELATIVE}: ${snapshot.templateCount} template blocks, ${snapshot.scaleCount} scale blocks, ${snapshot.lineCount} lines.`);
}

function check(snapshot) {
    if (!existsSync(SNAPSHOT_PATH)) {
        console.error(`${SNAPSHOT_RELATIVE} does not exist.`);
        console.error(FIX_HINT);
        process.exitCode = 1;
        return;
    }

    const committed = readFileSync(SNAPSHOT_PATH, 'utf8');
    if (committed === snapshot.text) {
        console.log(`Catalogue snapshot is up to date: ${snapshot.templateCount} template blocks, ${snapshot.scaleCount} scale blocks.`);
        return;
    }

    // Two ways to differ that a block-by-block comparison would only garble
    // (every header line would look changed), so they are named plainly instead.
    if (committed.includes('\r')) {
        console.error('The committed snapshot contains carriage returns (a CRLF checkout?). It must use LF line endings.');
        console.error(FIX_HINT);
        process.exitCode = 1;
        return;
    }

    const diff = unifiedDiff(committed, snapshot.text, {
        oldLabel: `${SNAPSHOT_RELATIVE} (committed)`,
        newLabel: `${SNAPSHOT_RELATIVE} (regenerated)`,
        headingPattern: /^## /
    });
    if (diff.length === 0) {
        console.error('The committed snapshot differs from a regeneration only in its final newline.');
        console.error(FIX_HINT);
        process.exitCode = 1;
        return;
    }

    const before = parseBlocks(committed);
    const after = parseBlocks(snapshot.text);
    const changed = [...after.keys()].filter(header => before.has(header) && before.get(header) !== after.get(header));
    const added = [...after.keys()].filter(header => !before.has(header));
    const removed = [...before.keys()].filter(header => !after.has(header));

    console.error(`Catalogue snapshot is out of date: ${changed.length} blocks changed, ${added.length} added, ${removed.length} removed.`);
    const named = [
        ...changed.map(header => `  changed  ${header}`),
        ...added.map(header => `  added    ${header}`),
        ...removed.map(header => `  removed  ${header}`)
    ];
    named.slice(0, CHANGED_BLOCKS_LISTED).forEach(line => console.error(line));
    if (named.length > CHANGED_BLOCKS_LISTED) console.error(`  ... and ${named.length - CHANGED_BLOCKS_LISTED} more`);
    console.error('');

    diff.slice(0, DIFF_LINES_SHOWN).forEach(line => console.error(line));
    if (diff.length > DIFF_LINES_SHOWN) console.error(`... ${diff.length - DIFF_LINES_SHOWN} more diff lines`);

    console.error('');
    console.error(FIX_HINT);
    process.exitCode = 1;
}

function main() {
    const [flag, ...extra] = process.argv.slice(2);
    if ((flag !== '--write' && flag !== '--check') || extra.length > 0) {
        console.error('Usage: node tools/catalogue-snapshot.mjs --write | --check');
        console.error('');
        console.error(`  --write   regenerate ${SNAPSHOT_RELATIVE}`);
        console.error('  --check   exit 1 if a regeneration would differ from the committed file');
        process.exitCode = 2;
        return;
    }

    const snapshot = buildSnapshot();
    if (flag === '--write') write(snapshot);
    else check(snapshot);
}

main();
